/*Instalar o .NET SDK: Baixe e instale a versão mais recente do .NET SDK no site oficial. 
Isso é essencial para compilar o código.
Configurar o VS Code:
Abra o VS Code e vá na aba de Extensões (Ctrl + Shift + X).
Pesquise por C# e instale o pacote "C# Dev Kit" da Microsoft.
Criar o Projeto:
Abra uma pasta vazia no VS Code (File > Open Folder).
Abra o terminal integrado (Ctrl + Shift + ').
Digite: dotnet new console e pressione Enter para criar um novo projeto "Olá Mundo".
Executar o Código:
Abra o arquivo Program.cs para editar seu código. */
